"""Check that the released TPx companion still supports every number in the paper.

Run from the repository root::

    python3 validate_public_companion.py

Sections:

1. corpus structure (rows, unique identifiers, allowed labels, scope
   decisions, bibliography, frozen sheet, descriptive table);
2. published counts, regenerated by ``corpus/regenerate_paper_counts.py``
   and compared with the values stated in the publication;
3. coverage updates (June 5 candidate log and search log, June 8 follow-up);
4. reliability audit (sample, agreement, kappa, Jaccard, reconciliation);
5. reporting cards, validated against the JSON Schema by
   ``reporting_card/validate_cards.py`` (needs PyYAML and jsonschema from
   ``requirements.txt``).

``corpus/CONSISTENCY_CHECK.md`` lists the same checks in prose; keep both in
sync when either changes.
"""
